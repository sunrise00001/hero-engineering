/**
  * @brief This function handles USART3 global interrupt.
  */
void USART3_IRQHandler(void)
{
  /* USER CODE BEGIN USART3_IRQn 0 */
	// 检查接收数据寄存器非空标志；读取 SR、DR 清除 RXNE。
	if(huart3.Instance->SR & UART_FLAG_RXNE)
    {
        __HAL_UART_CLEAR_PEFLAG(&huart3);
    }
    // 检测到串口空闲时，统计本次 DMA 接收长度并切换接收缓冲区。
    else if(USART3->SR & UART_FLAG_IDLE)
    {
        static uint16_t this_time_rx_len = 0;

        // 依次读取 SR、DR 清除 IDLE 标志，避免重复进入空闲中断。
        __HAL_UART_CLEAR_PEFLAG(&huart3);

        if ((hdma_usart3_rx.Instance->CR & DMA_SxCR_CT) == RESET)
        {
            // CT = 0：DMA 当前使用缓冲区 0，本次接收数据从该缓冲区读取。

            // 暂停 DMA，准备重置接收计数并切换缓冲区。
            __HAL_DMA_DISABLE(&hdma_usart3_rx);

            // 本次接收字节数 = 缓冲区容量 - DMA 剩余传输数量。
            this_time_rx_len = SBUS_RX_BUF_NUM - hdma_usart3_rx.Instance->NDTR;

            // 重新设置下一次接收的传输数量。
            hdma_usart3_rx.Instance->NDTR = SBUS_RX_BUF_NUM;

            // 将后续 DMA 接收切换到缓冲区 1，便于解析缓冲区 0。
            hdma_usart3_rx.Instance->CR |= DMA_SxCR_CT;

            // 恢复 DMA 接收。
            __HAL_DMA_ENABLE(&hdma_usart3_rx);

            // 仅当本次收到完整的 18 字节遥控帧时，解析并更新遥控数据。
            if(this_time_rx_len == RC_FRAME_LENGTH)
            {
                RemoteData_extract(sbus_rx_buf[0], &RC_ctrldata);
            }
        }
        else
        {
            // CT = 1：DMA 当前使用缓冲区 1，本次接收数据从该缓冲区读取。
            // 暂停 DMA，准备重置接收计数并切换缓冲区。
            __HAL_DMA_DISABLE(&hdma_usart3_rx);

            // 本次接收字节数 = 缓冲区容量 - DMA 剩余传输数量。
            this_time_rx_len = SBUS_RX_BUF_NUM - hdma_usart3_rx.Instance->NDTR;

            // 重新设置下一次接收的传输数量。
            hdma_usart3_rx.Instance->NDTR = SBUS_RX_BUF_NUM;

            // 将后续 DMA 接收切换到缓冲区 0，便于解析缓冲区 1。
            DMA1_Stream1->CR &= ~(DMA_SxCR_CT);

            // 恢复 DMA 接收。
            __HAL_DMA_ENABLE(&hdma_usart3_rx);

            // 仅当本次收到完整的 18 字节遥控帧时，解析并更新遥控数据。
            if(this_time_rx_len == RC_FRAME_LENGTH)
            {
              RemoteData_extract(sbus_rx_buf[1], &RC_ctrldata);
                // 可选：通过 USART1 转发原始遥控帧（当前未启用）。
                //sbus_to_usart1(sbus_rx_buf[1]);
            }
        }
    }
  /* USER CODE END USART3_IRQn 0 */
  HAL_UART_IRQHandler(&huart3);
  /* USER CODE BEGIN USART3_IRQn 1 */

  /* USER CODE END USART3_IRQn 1 */
}

