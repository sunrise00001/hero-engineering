/**
  * @brief This function handles USART6 global interrupt.
  */
void USART6_IRQHandler(void)
{
  /* USER CODE BEGIN USART6_IRQn 0 */
  if (RESET != __HAL_UART_GET_FLAG(&huart6, UART_FLAG_IDLE))    //判断是否发生空闲中断
  {
    __HAL_UART_CLEAR_IDLEFLAG(&huart6);                         //清除空闲标志

    int len = 256 - __HAL_DMA_GET_COUNTER(&hdma_usart6_rx);     //计算实际接收长度

    parse(referee_buff,len);
    memset(referee_buff,0,len);
    HAL_UART_Receive_DMA(&huart6, referee_buff,256);
  }

  /* USER CODE END USART6_IRQn 0 */
  HAL_UART_IRQHandler(&huart6);
  /* USER CODE BEGIN USART6_IRQn 1 */

  /* USER CODE END USART6_IRQn 1 */
}

